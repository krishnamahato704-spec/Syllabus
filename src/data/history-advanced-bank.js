export function getHistoryQuestion(section, index, testSalt = 0) {
  let bank = ANCIENT_HISTORY_BANK;
  if (section === 'medieval') bank = MEDIEVAL_HISTORY_BANK;
  else if (section === 'modern') bank = MODERN_HISTORY_BANK;
  else if (section === 'historiography') bank = HISTORIOGRAPHY_BANK;
  else {
    // Mixed / Core History: cycle across all 4 domains
    const combined = [...ANCIENT_HISTORY_BANK, ...MEDIEVAL_HISTORY_BANK, ...MODERN_HISTORY_BANK, ...HISTORIOGRAPHY_BANK];
    const i = (index + testSalt * 13) % combined.length;
    const base = combined[i];
    return {
      q: base.q,
      options: [...base.opts],
      correctAnswer: base.ans,
      explanation: base.exp
    };
  }

  const i = (index + testSalt * 7) % bank.length;
  const base = bank[i];
  return {
    q: base.q,
    options: [...base.opts],
    correctAnswer: base.ans,
    explanation: base.exp
  };
}
